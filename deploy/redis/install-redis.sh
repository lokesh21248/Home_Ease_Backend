#!/bin/bash
# ==============================================================================
# HOME EASE – Redis Installation Script (Ubuntu 22.04 / Amazon Linux 2023)
# Run as: sudo bash install-redis.sh
# ==============================================================================

set -euo pipefail

REDIS_PASSWORD="${REDIS_PASSWORD:-CHANGE_ME_BEFORE_RUNNING}"
BACKEND_PRIVATE_IP="${BACKEND_PRIVATE_IP:-10.0.1.20}"
REDIS_MAXMEMORY="${REDIS_MAXMEMORY:-400mb}"  # 400 MB for t4g.small, 800mb for t4g.medium

echo "=============================================="
echo " HomeEase Phase 1 – Redis Installer"
echo " Backend Private IP : $BACKEND_PRIVATE_IP"
echo " Max Memory         : $REDIS_MAXMEMORY"
echo "=============================================="

# ── 1. Install Redis ──────────────────────────────────────────────────────────
if command -v apt-get &> /dev/null; then
    apt-get update -y
    apt-get install -y redis-server
elif command -v dnf &> /dev/null; then
    dnf install -y redis
else
    echo "ERROR: Neither apt-get nor dnf found. Install Redis manually."
    exit 1
fi

# ── 2. Disable Transparent Huge Pages (THP) ───────────────────────────────────
echo "never" > /sys/kernel/mm/transparent_hugepage/enabled
echo "never" > /sys/kernel/mm/transparent_hugepage/defrag

# Make THP disable persistent across reboots
cat > /etc/systemd/system/disable-thp.service <<EOF
[Unit]
Description=Disable Transparent Huge Pages (THP)
DefaultDependencies=no
After=sysinit.target local-fs.target
Before=mongod.service redis.service

[Service]
Type=oneshot
ExecStart=/bin/sh -c 'echo never > /sys/kernel/mm/transparent_hugepage/enabled'
ExecStart=/bin/sh -c 'echo never > /sys/kernel/mm/transparent_hugepage/defrag'

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable disable-thp.service
systemctl start disable-thp.service

# ── 3. Tune kernel for TCP performance ────────────────────────────────────────
sysctl -w net.core.somaxconn=512
echo "net.core.somaxconn=512" >> /etc/sysctl.d/99-homeease-redis.conf
sysctl -w vm.overcommit_memory=1
echo "vm.overcommit_memory=1" >> /etc/sysctl.d/99-homeease-redis.conf

# ── 4. Create Redis data and log directories ──────────────────────────────────
mkdir -p /var/lib/redis /var/log/redis
chown redis:redis /var/lib/redis /var/log/redis
chmod 750 /var/lib/redis

# ── 5. Write production Redis config ─────────────────────────────────────────
CONFIG_FILE="/etc/redis/redis.conf"

cp "$CONFIG_FILE" "${CONFIG_FILE}.bak.$(date +%Y%m%d_%H%M%S)"

cat > "$CONFIG_FILE" <<REDIS_CONF
# HomeEase Phase 1 Redis Configuration
# Generated by install-redis.sh at $(date)

bind 127.0.0.1 ${BACKEND_PRIVATE_IP}
protected-mode yes
port 6379
tcp-backlog 511
tcp-keepalive 300
tcp-nodelay yes

requirepass ${REDIS_PASSWORD}
rename-command FLUSHALL   ""
rename-command FLUSHDB    ""
rename-command DEBUG      ""
rename-command CONFIG     "homeease-config-9x3"
rename-command SHUTDOWN   "homeease-shutdown-7z2"

maxmemory ${REDIS_MAXMEMORY}
maxmemory-policy allkeys-lru
maxclients 4096
timeout 0

save 900 1
save 300 10
save 60  1000

appendonly yes
appendfilename "redis-homeease.aof"
appendfsync everysec
no-appendfsync-on-rewrite no
auto-aof-rewrite-percentage 100
auto-aof-rewrite-min-size 64mb

dir /var/lib/redis
dbfilename dump-homeease.rdb

slowlog-log-slower-than 10000
slowlog-max-len 256
latency-monitor-threshold 25
latency-tracking yes

lazyfree-lazy-eviction yes
lazyfree-lazy-expire yes
lazyfree-lazy-server-del yes
replica-lazy-flush yes

loglevel notice
logfile /var/log/redis/redis-server.log
REDIS_CONF

# ── 6. Enable and start Redis ─────────────────────────────────────────────────
systemctl daemon-reload
systemctl enable redis
systemctl restart redis

# ── 7. Verify Redis is running and authenticated ──────────────────────────────
sleep 2

echo ""
echo "── Redis Health Check ────────────────────────────────────────────────────"
if redis-cli -a "$REDIS_PASSWORD" PING 2>/dev/null | grep -q PONG; then
    echo "  ✅ Redis is running and password authentication works."
else
    echo "  ❌ Redis PING failed. Check /var/log/redis/redis-server.log"
    journalctl -u redis --no-pager -n 20
    exit 1
fi

echo ""
echo "── Verifying Redis is NOT listening on 0.0.0.0 ──────────────────────────"
if ss -tlnp | grep -E '0.0.0.0:6379|:::6379'; then
    echo "  ❌ DANGER: Redis is exposed on 0.0.0.0. Fix bind in /etc/redis/redis.conf immediately."
    exit 1
else
    echo "  ✅ Redis is NOT publicly exposed (listening on localhost + private IP only)."
fi

echo ""
echo "── Redis Server Info ─────────────────────────────────────────────────────"
redis-cli -a "$REDIS_PASSWORD" INFO server | grep -E "redis_version|tcp_port|bound_addresses|config_file"

echo ""
echo "── Redis Memory Info ─────────────────────────────────────────────────────"
redis-cli -a "$REDIS_PASSWORD" INFO memory | grep -E "used_memory_human|maxmemory_human|maxmemory_policy|mem_fragmentation_ratio"

echo ""
echo "=============================================="
echo " ✅ Redis Phase 1 Installation Complete"
echo "=============================================="
echo ""
echo " Connection String for Spring Boot:"
echo "   REDIS_HOST=127.0.0.1"
echo "   REDIS_PORT=6379"
echo "   REDIS_PASSWORD=${REDIS_PASSWORD}"
echo ""
echo " ⚠️  IMPORTANT: Set REDIS_PASSWORD as an environment variable in your"
echo "    Spring Boot application.yml or systemd service file."
echo "    DO NOT commit the password to source control."
echo ""
